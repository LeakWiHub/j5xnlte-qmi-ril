#!/system/bin/sh
# Device-side logic of install / enable / rollback. Runs as root on the phone (via scripts/install.sh) and,
# for tests, on the host with J5_ROOT=<fake root> J5_TEST=1 (see tests/install/test_install.sh).
# Principles: never two RILs at once; never touch SELinux mode; never chmod 666; every change is recorded
# in a manifest so that `rollback` can undo exactly it. Not verified on a real device (see README_RU.md).
R="${J5_ROOT:-}"
STATE="$R/data/local/tmp/j5ril-state"       # manifest + backups live here (survives until rollback finishes)
NODE_PATH="${J5_NODE:-/dev/wwan0qmi0}"
BIN_DST=/vendor/bin/hw/android.hardware.radio-service.j5xnlte-qmi
RC_DST=/vendor/etc/init/init.j5xnlte-ril.rc
MODRC_DST=/vendor/etc/init/init.j5xnlte-modem-modules.rc
VINTF_DST=/vendor/etc/vintf/manifest/android.hardware.radio.j5xnlte-qmi.xml
UEV_DST=/vendor/etc/ueventd.rc
OURSVC=vendor.j5xnlte-ril
PROP=persist.vendor.j5ril.enable
BEGIN='# >>> j5xnlte-ril >>>'
END='# <<< j5xnlte-ril <<<'

die() { echo "ERROR: $*" >&2; exit 1; }
say() { echo "$*"; }

# ---- thin wrappers so that the logic can run against a fake root ------------------------------------------
_getprop() { if [ -n "$J5_TEST" ]; then cat "$R/props/$1" 2>/dev/null; else getprop "$1"; fi; }
_setprop() { if [ -n "$J5_TEST" ]; then mkdir -p "$R/props"; printf '%s' "$2" >"$R/props/$1"; _test_react "$1" "$2"; else setprop "$1" "$2"; fi; }
_enforce() { if [ -n "$J5_TEST" ]; then cat "$R/enforce" 2>/dev/null || echo Enforcing; else getenforce; fi; }
_chcon() { if [ -n "$J5_TEST" ]; then [ -e "$R/policy_ok" ] || return 1; else chcon "$@"; fi; }
_svc_ctl() { # $1 start|stop $2 name
  if [ -n "$J5_TEST" ]; then mkdir -p "$R/props"; if [ "$1" = start ]; then printf running >"$R/props/init.svc.$2"; else printf stopped >"$R/props/init.svc.$2"; fi; echo "$1 $2" >>"$R/svc.log"
    if [ "$1" = stop ]; then for d in "$R"/proc/[0-9]*; do [ "$(cat "$d/svc" 2>/dev/null)" = "$2" ] && rm -rf "$d"; done; fi
  else "$1" "$2"; fi; }
_svc_state() { _getprop "init.svc.$1"; }
_all_svcs() { # names of all services init knows about
  if [ -n "$J5_TEST" ]; then ls "$R/props" 2>/dev/null | sed -n 's/^init\.svc\.//p'; else getprop | sed -n 's/^\[init\.svc\.\(.*\)\]: \[.*$/\1/p'; fi; }
_test_react() { # test-only imitation of the init.rc triggers generated by this project
  [ "$1" = "$PROP" ] || return 0
  grep -q 'j5xnlte-ril' "$R$RC_DST" 2>/dev/null || return 0
  if [ "$2" = 1 ]; then
    for s in $(sed -n 's/^    stop \(.*\)$/\1/p' "$R$RC_DST" | sort -u); do [ "$s" = "$OURSVC" ] || _svc_ctl stop "$s"; done
    [ -e "$R/force_ours_fail" ] || _svc_ctl start "$OURSVC"
    [ -e "$R/force_ours_fail" ] && { printf stopped >"$R/props/init.svc.$OURSVC"; echo "start $OURSVC (fails)" >>"$R/svc.log"; }
  else
    _svc_ctl stop "$OURSVC"
    for s in $(sed -n 's/^    start \(.*\)$/\1/p' "$R$RC_DST" | sort -u); do [ "$s" = "$OURSVC" ] || _svc_ctl start "$s"; done
  fi
}

old_candidates() { _all_svcs | grep -i 'ril' | grep -v "^$OURSVC\$" | sort -u; }

node_holders() { # prints "pid cmdline" for every process holding the QMI node open (needs root)
  for fd in "$R"/proc/[0-9]*/fd/*; do
    [ -e "$fd" ] || [ -L "$fd" ] || continue
    t=$(readlink "$fd" 2>/dev/null) || continue
    [ "$t" = "$NODE_PATH" ] || continue
    pid=${fd#"$R"/proc/}; pid=${pid%%/*}
    echo "$pid $(tr '\0' ' ' <"$R/proc/$pid/cmdline" 2>/dev/null)"
  done
}

cmd_preflight() {
  rc=0
  [ "$(id -u)" = 0 ] || [ -n "$J5_TEST" ] || { say "FAIL: not root"; rc=1; }
  [ -c "$R$NODE_PATH" ] || [ -e "$R$NODE_PATH" ] || say "WARN: $NODE_PATH does not exist (on the real phone it appeared only after: insmod /vendor/lib/modules/rpmsg_wwan_ctrl.ko qcom_bam_dmux.ko rmnet.ko). --install adds an init rc that loads them; --enable needs the node."
  say "SELinux: $(_enforce) (this project never changes it; must stay Enforcing)"
  [ "$(_enforce)" = Enforcing ] || { say "FAIL: SELinux is not Enforcing; refusing to continue"; rc=1; }
  h=$(node_holders)
  if [ -n "$h" ]; then say "node holders:"; echo "$h" | sed 's/^/  /'; else say "node holders: none"; fi
  say "candidate old RIL services (pass the ones to switch off via --stop-old):"
  for s in $(old_candidates); do say "  $s  state=$(_svc_state "$s")"; done
  if grep -rl 'android.hardware.radio' "$R/vendor/etc/vintf" "$R/vendor/manifest.xml" 2>/dev/null | grep -v j5xnlte >/dev/null 2>&1; then
    say "WARN: another vendor manifest declares android.hardware.radio.*; same-instance declarations conflict."
    say "      Check it before --enable (a conflict can break boot: that is why --enable is a separate step)."
  fi
  return $rc
}

backup_file() { # $1 device path -> STATE/backup/<path>
  [ -e "$R$1" ] || return 0
  mkdir -p "$STATE/backup$(dirname "$1")"; cp -p "$R$1" "$STATE/backup$1" || die "backup of $1 failed"
}

cmd_install() { # install <binary> <rc.in> <vintf.xml> <ueventd-fragment|-> <stop-old list, may be empty> [modules.rc]
  bin=$1; rcin=$2; vintf=$3; uev=$4; stopold=$5; modrc=$6
  [ -f "$STATE/manifest" ] && die "already installed (manifest exists); run rollback first"
  [ -f "$bin" ] && [ -f "$rcin" ] && [ -f "$vintf" ] || die "input files missing"
  cmd_preflight || die "preflight failed"
  [ -z "$(node_holders)" ] || say "note: the node is held right now (by the old RIL?). It stays so until --enable."
  for s in $stopold; do [ -n "$(_svc_state "$s")" ] || die "unknown service '$s'"; done
  mkdir -p "$STATE"; : >"$STATE/manifest"
  echo "stopold $stopold" >>"$STATE/manifest"
  # remember which of them were running (rollback restarts exactly those)
  for s in $stopold; do echo "was $s $(_svc_state "$s")" >>"$STATE/manifest"; done

  for f in $BIN_DST $RC_DST $VINTF_DST $UEV_DST $MODRC_DST; do backup_file "$f"; done
  for f in $BIN_DST $RC_DST $VINTF_DST; do
    [ -e "$R$f" ] && die "$f already exists and is not ours; refusing to overwrite"
  done

  mkdir -p "$R$(dirname $BIN_DST)" "$R$(dirname $RC_DST)" "$R$(dirname $VINTF_DST)"
  cp "$bin" "$R$BIN_DST" && echo "added $BIN_DST" >>"$STATE/manifest" || die "copy binary failed"
  chmod 0755 "$R$BIN_DST"
  # the SELinux type must exist in the loaded policy: chcon fails otherwise -> we undo everything
  if ! _chcon u:object_r:j5qmi_ril_exec:s0 "$R$BIN_DST"; then
    echo "SELinux type j5qmi_ril_exec is not in the loaded policy; rolling back (see README_RU.md: policy must be built into the vendor image first)" >&2
    cmd_rollback; exit 1
  fi
  # init rc from the template: only the services the user named are stopped/started by our triggers
  stopl=""; startl=""
  for s in $stopold; do stopl="$stopl    stop $s
"; startl="$startl    start $s
"; done
  awk -v stop="$stopl" -v start="$startl" '
    /^@STOP_OLD@$/ { printf "%s", stop; next }
    /^@START_OLD@$/ { printf "%s", start; next }
    { print }' "$rcin" >"$R$RC_DST" || die "rc write failed"
  chmod 0644 "$R$RC_DST"; _chcon u:object_r:vendor_configs_file:s0 "$R$RC_DST" 2>/dev/null
  echo "added $RC_DST" >>"$STATE/manifest"
  cp "$vintf" "$R$VINTF_DST"; chmod 0644 "$R$VINTF_DST"; _chcon u:object_r:vendor_configs_file:s0 "$R$VINTF_DST" 2>/dev/null
  echo "added $VINTF_DST" >>"$STATE/manifest"
  if [ -n "$modrc" ] && [ -f "$modrc" ] && [ ! -e "$R$MODRC_DST" ]; then
    cp "$modrc" "$R$MODRC_DST"; chmod 0644 "$R$MODRC_DST"; _chcon u:object_r:vendor_configs_file:s0 "$R$MODRC_DST" 2>/dev/null
    echo "added $MODRC_DST" >>"$STATE/manifest"
  fi
  # ueventd: add the node permission only if the current rules do not already give the radio user access
  if [ "$uev" != - ] && [ -f "$R$UEV_DST" ] && ! grep -Eq "^$NODE_PATH[[:space:]]+0660[[:space:]]+radio[[:space:]]+radio" "$R$UEV_DST"; then
    { echo "$BEGIN"; grep -v '^#' "$uev"; echo "$END"; } >>"$R$UEV_DST"
    echo "edited $UEV_DST" >>"$STATE/manifest"
  fi
  say "installed. The old RIL is untouched and ${OURSVC} is NOT running: nothing switched yet."
  say "next: install.sh --enable   (switches), install.sh --rollback (undoes everything)"
}

wait_state() { # $1 service $2 wanted state $3 seconds
  i=0; while [ $i -lt "$3" ]; do [ "$(_svc_state "$1")" = "$2" ] && return 0; [ -n "$J5_TEST" ] || sleep 1; i=$((i+1)); done; return 1
}

cmd_enable() {
  [ -f "$STATE/manifest" ] || die "not installed"
  [ -f "$R$BIN_DST" ] && [ -f "$R$RC_DST" ] || die "installed files missing"
  [ -e "$R$NODE_PATH" ] || die "$NODE_PATH does not exist: load the modem modules first (see preflight), refusing to switch"
  stopold=$(sed -n 's/^stopold //p' "$STATE/manifest")
  [ -n "$(node_holders)" ] && [ -z "$stopold" ] && die "the QMI node is held by another process and no --stop-old services were given: refusing to run two RILs"
  say "switching: stop [$stopold] -> start $OURSVC"
  # the rc trigger does stop-then-start; we verify the result instead of trusting it
  _setprop $PROP 1
  for s in $stopold; do
    wait_state "$s" stopped 10 || { say "old service $s did not stop"; cmd_disable_internal; die "switch failed, old RIL restored"; }
  done
  if [ -n "$(node_holders | grep -v "j5xnlte")" ]; then
    say "the QMI node is still held by:"; node_holders | sed 's/^/  /'
    cmd_disable_internal; die "node still held by a foreign process, switch undone"
  fi
  wait_state $OURSVC running 10 || { say "$OURSVC is not running"; cmd_disable_internal; die "new RIL did not start, old RIL restored"; }
  say "switched. Check with: logcat -s j5xnlte-ril ; dumpsys telephony.registry"
}

cmd_disable_internal() { # undo the switch without removing files
  _setprop $PROP 0
  _svc_ctl stop $OURSVC
  stopold=$(sed -n 's/^stopold //p' "$STATE/manifest" 2>/dev/null)
  for s in $stopold; do
    was=$(sed -n "s/^was $s //p" "$STATE/manifest")
    [ "$was" = running ] && { [ "$(_svc_state "$s")" = running ] || _svc_ctl start "$s"; }
  done
}

cmd_rollback() {
  [ -d "$STATE" ] || { say "nothing to roll back"; return 0; }
  cmd_disable_internal
  if [ -f "$STATE/manifest" ]; then
    while read -r kind path; do
      case $kind in
        added) rm -f "$R$path" ;;
        edited) # only our marked block is removed; the original file is restored from backup if it still matches
          if [ -f "$STATE/backup$path" ]; then cp -p "$STATE/backup$path" "$R$path"; else
            sed "/^$BEGIN\$/,/^$END\$/d" "$R$path" >"$R$path.j5tmp" && mv "$R$path.j5tmp" "$R$path"; fi ;;
      esac
    done <"$STATE/manifest"
  fi
  _setprop $PROP ""
  rm -rf "$STATE"
  say "rolled back: files removed, old RIL services restored to their previous state"
}

cmd_status() {
  [ -f "$STATE/manifest" ] && { echo "installed:"; cat "$STATE/manifest"; } || echo "not installed"
  echo "$PROP=$(_getprop $PROP)"; echo "$OURSVC: $(_svc_state $OURSVC)"
  node_holders
}

case "${1:-}" in
  preflight) cmd_preflight ;;
  install) shift; cmd_install "$@" ;;
  enable) cmd_enable ;;
  disable) cmd_disable_internal; say "switch undone (files stay)" ;;
  rollback) cmd_rollback ;;
  status) cmd_status ;;
  *) echo "usage: $0 preflight|install ...|enable|disable|rollback|status" >&2; exit 2 ;;
esac
