"""Generates RadioXxxBase.h for the Radio AIDL HAL interfaces from the FROZEN .aidl snapshots.

Every request of an interface gets a default implementation that answers REQUEST_NOT_SUPPORTED through the
matching *Response method (never an empty "success"). The concrete HAL classes derive from these bases and
override only what the QMI backend really implements, so an unimplemented method fails loudly and visibly.

usage: gen_hal_base.py <aidl_api_dir> <version> <out_dir>
Reuses the AIDL parser of tools/aidl-mock/gen_aidl_headers.py (same type resolution rules).
"""
import os, re, sys
sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "aidl-mock"))
import gen_aidl_headers as g

IFACES = [("config", "IRadioConfig"), ("modem", "IRadioModem"), ("sim", "IRadioSim"), ("network", "IRadioNetwork"),
          ("messaging", "IRadioMessaging"), ("voice", "IRadioVoice"), ("data", "IRadioData")]
RESP_ALIAS = {("IRadioVoice", "hangup"): "hangupConnectionResponse"}   # the one irregular name in V1..V4
ACK_ONLY = {"responseAcknowledgement"}     # no response method exists, the base just returns ok


def methods(body):
    out = []
    for m in body:
        if m[0] != "stmt":
            continue
        mm = re.match(r"^oneway void (\w+)\((.*)\)$", " ".join(m[1].split()))
        if not mm:
            raise SystemExit("bad method " + m[1])
        out.append((mm.group(1), mm.group(2)))
    return out


def sig_of(iface_pkg, iface, params):
    ps, names = [], []
    for p in g.split_top(params):
        t, n, nl = g.parse_param(p)
        kk, inner = g.base_type(t)
        ty = g.by_value(t, nl, iface_pkg, [iface])
        if kk == "one" and inner not in g.PRIM and inner != "String" and g.is_iface(g.resolve(inner, iface_pkg, [iface])):
            ty = "const std::shared_ptr<%s>&" % g.cpp_name(g.resolve(inner, iface_pkg, [iface]))
        ps.append("[[maybe_unused]] %s in_%s" % (ty, n))
        names.append(n)
    return ps, names


def gen_recorders(by_name, out):
    """Test helper: classes implementing every Response/Indication method by recording "name[:error]" in a log."""
    for sub, iface in IFACES:
        pkg = "android.hardware.radio." + sub
        ns = "::aidl::" + pkg.replace(".", "::")
        L = ["// GENERATED test recorders - not part of the HAL binary. SPDX-License-Identifier: Apache-2.0", "#pragma once", "",
             "#include <optional>", "#include <string>", "#include <vector>", '#include "recorder.h"',
             "#include <aidl/%s/Bn%sResponse.h>" % (pkg.replace(".", "/"), iface[1:]),
             "#include <aidl/%s/Bn%sIndication.h>" % (pkg.replace(".", "/"), iface[1:]), ""]
        for suffix in ("Response", "Indication"):
            body = by_name[(pkg, iface + suffix)]
            cls = "%sRec%s" % (iface[1:], suffix)
            L.append("class %s : public %s::Bn%s%s, public Recorder {" % (cls, ns, iface[1:], suffix))
            L.append(" public:")
            for name, params in methods(body):
                ps, names = sig_of(pkg, iface + suffix, params)
                if suffix == "Response" and "RadioResponseInfo" in ps[0]:
                    arg = "in_" + names[0]
                    rec = 'add("%s:" + std::to_string(static_cast<int>(%s.error)));' % (name, arg)
                else:
                    rec = 'add("%s");' % name
                L.append("    ::ndk::ScopedAStatus %s(%s) override { %s return ::ndk::ScopedAStatus::ok(); }" % (name, ", ".join(ps), rec))
            L.append("};")
            L.append("")
        open(os.path.join(out, "Rec_%s.h" % iface[1:]), "w").write("\n".join(L) + "\n")


def main():
    api, ver, out = sys.argv[1:4]
    g.configure(api, ver, out)
    g.load()
    g.top_level = set()
    for pkg, kind, name, ann, body in g.files:
        g.top_level.add(pkg + "." + name)
        g.register(pkg, kind, name, ann, body)
    by_name = {(pkg, name): body for pkg, kind, name, ann, body in g.files if kind == "interface"}
    os.makedirs(out, exist_ok=True)
    if len(sys.argv) > 4 and sys.argv[4] == "--recorders":
        gen_recorders(by_name, out)
        return
    for sub, iface in IFACES:
        pkg = "android.hardware.radio." + sub
        body = by_name[(pkg, iface)]
        rbody = by_name[(pkg, iface + "Response")]
        resp = {n: p for n, p in methods(rbody)}
        cls = iface[1:] + "Base"
        ns = "::aidl::" + pkg.replace(".", "::")
        L = ["// GENERATED by tools/gen-hal-base/gen_hal_base.py from the frozen V%s AIDL - do not edit. SPDX-License-Identifier: Apache-2.0" % ver,
             "#pragma once", "",
             "#include <memory>", "#include <optional>", "#include <string>", "#include <vector>", "",
             "#include <aidl/%s/Bn%s.h>" % (pkg.replace(".", "/"), iface[1:]),
             "#include <aidl/%s/%sResponse.h>" % (pkg.replace(".", "/"), iface),
             "#include <aidl/%s/%sIndication.h>" % (pkg.replace(".", "/"), iface),
             '#include "response_info.h"', "",
             "class %s : public %s::Bn%s {" % (cls, ns, iface[1:]),
             " protected:",
             "    std::shared_ptr<%s::%sResponse> mResp;" % (ns, iface),
             "    std::shared_ptr<%s::%sIndication> mInd;" % (ns, iface),
             "    virtual void onResponseFunctionsSet() {}", "",
             " public:"]
        seen_set = False
        for name, params in methods(body):
            ps = []
            names = []
            for p in g.split_top(params):
                t, n, nl = g.parse_param(p)
                kk, inner = g.base_type(t)
                ty = g.by_value(t, nl, pkg, [iface])
                if kk == "one" and inner not in g.PRIM and inner != "String" and g.is_iface(g.resolve(inner, pkg, [iface])):
                    ty = "const std::shared_ptr<%s>&" % g.cpp_name(g.resolve(inner, pkg, [iface]))
                unused = "[[maybe_unused]] " if (len(names) > 0 and name != "setResponseFunctions") else ""
                ps.append("%s%s in_%s" % (unused, ty, n))
                names.append(n)
            sig = "    ::ndk::ScopedAStatus %s(%s) override {" % (name, ", ".join(ps))
            if name == "setResponseFunctions":
                seen_set = True
                L += [sig, "        mResp = in_%s;" % names[0], "        mInd = in_%s;" % names[1],
                      "        onResponseFunctionsSet();", "        return ::ndk::ScopedAStatus::ok();", "    }"]
            elif name in ACK_ONLY:
                L += [sig, "        return ::ndk::ScopedAStatus::ok();", "    }"]
            else:
                rn = RESP_ALIAS.get((iface, name), name + "Response")
                if rn not in resp:
                    raise SystemExit("no response method %s for %s.%s" % (rn, iface, name))
                rps = g.split_top(resp[rn])
                first = g.parse_param(rps[0])[0]
                helper = "modemNotSupported" if first.endswith("RadioResponseInfoModem") else "notSupported"
                if not (first.endswith("RadioResponseInfo") or first.endswith("RadioResponseInfoModem")):
                    raise SystemExit("unexpected first response arg %s in %s" % (first, rn))
                args = ", ".join([helper + "(in_%s)" % names[0]] + ["{}"] * (len(rps) - 1))
                L += [sig, "        if (mResp) mResp->%s(%s);" % (rn, args), "        return ::ndk::ScopedAStatus::ok();", "    }"]
        if not seen_set:
            raise SystemExit("%s has no setResponseFunctions" % iface)
        L.append("};")
        open(os.path.join(out, cls + ".h"), "w").write("\n".join(L) + "\n")
        print("generated %s (%d requests)" % (cls, len(methods(body))))


if __name__ == "__main__":
    main()
